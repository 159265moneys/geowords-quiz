import {LANGUAGES} from './data.js?v=20261006-4';

export function recognitionFor(question){
  const {word,language,shared}=question;
  const signs={
    DUR:{tone:'strong',label:'停止標識なら、ほぼ確定',text:'DUR の停止標識 → トルコ。通常のジオゲの道路カバレッジが前提。単語だけなら他言語の別義もあります。'},
    BERHENTI:{tone:'strong',label:'停止標識なら、ほぼ確定',text:'BERHENTI の停止標識 → マレーシア。通常のジオゲの道路カバレッジが前提。普通の文章ならインドネシア語にもあります。'},
    'ARRÊT':{tone:'strong',label:'地域の強い手がかり',text:'停止標識ならカナダのケベック州が有力。マニトバ州などにも例があり、州の100%確定にはなりません。'},
    ALTO:{tone:'shared',label:'国は複数候補',text:'停止標識ならメキシコ・グアテマラ・コスタリカ・パナマなど。ALTO だけで一国には確定できません。'},
    PARE:{tone:'shared',label:'言語も国も複数候補',text:'ブラジルのポルトガル語、南米各国のスペイン語で共通。停止標識でもブラジル確定ではありません。'}
  };
  if(signs[word])return signs[word];
  const distinctive=[
    ['de',/[ßẞ]/,'ß → ドイツ語の強い手がかり。ドイツとオーストリアなどの区別は、この文字だけではできません。'],
    ['hu',/[őűŐŰ]/,'二本のアクセントの ő・ű → ハンガリー語の非常に強い手がかり。設置国は周囲の表示も合わせます。'],
    ['pl',/[łŁ]/,'斜線付きの ł → ポーランド語の強い手がかり。他の少数言語にもあるため、世界全体での専用文字ではありません。'],
    ['cs',/[řěůŘĚŮ]/,'ř・ě・ů → チェコ語を強く示す組み合わせ。スロバキア語との比較に役立ちます。'],
    ['lt',/[ėĖ]/,'点付きの ė → リトアニア語の強い手がかり。ラトビア語の横棒とは区別します。'],
    ['uk',/[іїєґІЇЄҐ]/,'і・ї・є・ґ → ロシア語ではない手がかり。і だけは他言語にもあるので、残りの綴りを見ます。'],
    ['tr',/[ıİğĞ]/,'ı・İ・ğ → トルコ語を絞る手がかり。他のテュルク諸語でも使う文字があり、単独で世界共通の100%判定にはしません。'],
    ['vi',/[đơưấầẩẫậắằẳẵặếềểễệốồổỗộớờởỡợứừửữự]/,'母音に重なる記号や đ・ơ・ư → ベトナム語の強い手がかり。文字が読めなくても絞れます。']
  ];
  const distinctiveMatch=distinctive.find(([lang,pattern])=>language===lang&&pattern.test(word));
  if(distinctiveMatch)return {tone:'strong',label:'文字だけで強く絞れる',text:distinctiveMatch[2]};
  if(shared.length)return {tone:'shared',label:'この綴りは複数言語にある',text:'別の言語・別の意味・活用形にも同じ綴りがあります。この文字列だけで言語や国を100%確定することはできません。'};
  const scripts={
    ko:'ハングルの音節ブロック → 韓国語。通常の出題では韓国が有力ですが、外国語の看板もあるため設置国の保証とは別です。',
    ja:'漢字とひらがなの混在 → 日本語の強い手がかり。日本が有力でも、外国にある日本語の看板という例外はあります。',
    el:'λ・θ・ω・ς などのギリシャ文字 → ギリシャ語の強い手がかり。文字体系の識別と、設置国の確定は分けます。',
    he:'角張ったヘブライ文字 → ヘブライ語の強い手がかり。右から左に読む点だけではアラビア語と区別できません。',
    th:'タイ文字の形が強い手がかり。ラオ文字と似た書体もあり、輪の有無だけで100%とは判断しません。',
    km:'下に重なる字形がクメール文字の強い手がかり。書体で形が変わるので、タイ文字との比較が役立ちます。'
  };
  if(scripts[language])return {tone:'strong',label:'文字の形が強い手がかり',text:scripts[language]};
  return {tone:'compare',label:'単語の綴りで見分ける',text:`特徴的な一文字だけでは決められない語です。${LANGUAGES[language].name}の語として綴りを覚え、国は周囲の情報と合わせます。`};
}
