export function recognitionFor(question){
  const {word,language}=question;
  const result=(tone,label,cue,target,text,caution='')=>({tone,label,cue,target,text,caution});
  const signs={
    DUR:['トルコが有力','停止標識の DUR はトルコを選ぶ強い決め手。通常の道路カバレッジが前提です。','普通の文章の dur はフランス語などにもあります。'],
    BERHENTI:['マレーシアが有力','停止標識の BERHENTI はマレーシアを選ぶ強い決め手。通常の道路カバレッジが前提です。','普通の文章の berhenti はインドネシア語にもあります。'],
    'ARRÊT':['カナダが有力','停止標識ならカナダ、とくにケベック州が有力。フランス本国の停止標識は通常 STOP です。','ケベック州以外にも使われるため、州を決めるときは地名も見ます。']
  };
  if(signs[word])return result('strong','停止標識なら、強い決め手',word,...signs[word]);
  if(word==='ALTO')return result('shared','候補を絞る',word,'メキシコ・中米の一部','停止標識ならスペイン語。メキシコ・グアテマラ・コスタリカ・パナマなどが候補になります。');
  if(word==='PARE')return result('shared','言語・国の候補を絞る',word,'ポルトガル語／スペイン語','停止標識ならブラジルと南米のスペイン語圏が候補。ほかの語の ã・õ・-ção はポルトガル語を絞る手がかりです。');
  if(sharedUses[word])return result('shared','候補を絞る',word,...sharedUses[word]);
  if(contextUses[word])return result('compare','看板の用途とセット',word,...contextUses[word]);
  const distinctive=[
    ['de',/[ßẞ]/,'ß','斜線ではなく、B に似た ß がドイツ語の強い手がかり。ドイツ・オーストリアなどを候補にします。'],
    ['hu',/[őűŐŰ]/,'ő・ű','二本のアクセントがハンガリー語の強い手がかり。ö・ü の二つの点と区別します。'],
    ['pl',/[łŁ]/,'ł','l を斜線が横切る形を覚えれば、意味を読まずにポーランド語を強く絞れます。'],
    ['cs',/[řěůŘĚŮ]/,null,'ř・ě・ů はチェコ語とスロバキア語を分ける有用な文字。この単語の記号に注目します。'],
    ['lt',/[ėĖ]/,'ė','e の上の一点がリトアニア語の強い手がかり。ラトビア語の ē は横棒です。'],
    ['vi',/[đơưấầẩẫậắằẳẵặếềểễệốồổỗộớờởỡợứừửữự]/,null,'短い語の母音に記号が重なる形を覚えます。この綴りはベトナム語の強い手がかりです。']
  ];
  const match=distinctive.find(([lang,pattern])=>lang===language&&pattern.test(word));
  if(match)return result('strong','文字で見分ける',match[2]||[...new Set(word.match(new RegExp(match[1].source,'g')))].join('・'),LANGUAGES[language].name,match[3]);
  const scripts={
    ko:['ハングル','丸・四角・直線が音節ごとのブロックにまとまる形。単語の意味を覚える前から韓国語を見分ける手がかりになります。'],
    ja:['漢字＋ひらがな','「止」と「まれ」の組み合わせ。ひらがなを見つけるだけで日本語を強く絞れます。'],
    el:['ギリシャ文字','δ・λ・θ・ω・ς などの字形を覚えます。単語の意味より先に文字体系でギリシャ語を絞れます。'],
    he:['ヘブライ文字','角張った文字がつながらずに並ぶ形。曲線でつながるアラビア文字と比べると見分けやすくなります。'],
    th:['タイ文字','ถ・น・ร などの形と上下の記号を覚えます。輪だけに頼らず、文字全体をクメール文字・ラオ文字と比べます。'],
    km:['クメール文字','複雑な曲線と下に重なる字形を覚えます。タイ文字と並べて形の違いを学ぶと見分けやすくなります。']
  };
  if(scripts[language])return result('strong','文字の形で見分ける',scripts[language][0],LANGUAGES[language].name,scripts[language][1]);
  return result('compare','綴りを覚えれば使える',word,LANGUAGES[language].name,question.clue);
}
